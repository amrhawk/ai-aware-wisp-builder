"use strict";
/* Regenerates docs/QUESTIONNAIRE.md and templates/*.md from the source modules. Run: node scripts/build-docs.js */
const fs = require("fs"), path = require("path");
const root = path.join(__dirname, "..");
fs.writeFileSync(path.join(root, "docs", "QUESTIONNAIRE.md"), require("./questionnaire-md.js")() + "\n");
const T = require("../src/templates.js");
Object.keys(T).forEach(k => {
  if (k === "addendum") return;
  fs.writeFileSync(path.join(root, "templates", k + ".md"), `# ${T[k].title}\n\n${T[k].body}\n\n---\nText licensed CC BY 4.0. Guidance only; not legal advice.\n`);
});
console.log("docs and templates regenerated");
const sample = fs.readFileSync(path.join(root, "examples", "sample-answers-5-person-firm.json"), "utf8");
fs.writeFileSync(path.join(root, "web", "sample.js"), "/* generated by scripts/build-docs.js */\nwindow.WISP_SAMPLE = " + sample.trim() + ";\n");
console.log("web/sample.js regenerated");
